a = 10
b = 5

# AND operator
print("AND Operator:")
print(a > 5 and b < 10)   # True
print(a < 5 and b < 10)   # False

# OR operator
print("\nOR Operator:")
print(a > 5 or b > 10)    # True
print(a < 5 or b > 10)    # False

# NOT operator
print("\nNOT Operator:")
print(not (a > 5))        # False
print(not (b > 10))       # True